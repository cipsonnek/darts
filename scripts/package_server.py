"""Build the package for the central server (operator panel on a Linux VPS).

    .venv\\Scripts\\python.exe scripts\\package_server.py            # builds the UI, then packs
    .venv\\Scripts\\python.exe scripts\\package_server.py --no-build # pack the existing frontend/dist

Writes release/dartsense-serwer-YYYYMMDD-HHMM.tar.gz with the backend, the built UI, the
configs and deploy/ (install, update, backup scripts and web server configs). No data, no
virtualenv, no node_modules: the server installs its own Python packages.
"""

from __future__ import annotations

import argparse
import io
import shutil
import subprocess
import sys
import tarfile
import tomllib
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOP = "dartsense-serwer"
SKIP_DIRS = {"__pycache__", ".pytest_cache", "node_modules"}
# Files the server reads or runs as text: always with LF line endings.
TEXT_SUFFIXES = {".sh", ".service", ".conf", ".py", ".yaml", ".toml", ".md", ".txt", ".ini", ".mako"}


def build_frontend() -> None:
    npm = shutil.which("npm")
    if not npm:
        sys.exit("npm not found — install Node.js or use --no-build with an existing frontend/dist")
    print("Building the UI (npm run build)...")
    subprocess.run([npm, "run", "build"], cwd=ROOT / "frontend", check=True)


def requirements() -> str:
    deps = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["dependencies"]
    return "# generated by scripts/package_server.py from pyproject.toml\n" + "\n".join(deps) + "\n"


def add_bytes(tar: tarfile.TarFile, name: str, data: bytes, mode: int = 0o644) -> None:
    info = tarfile.TarInfo(f"{TOP}/{name}")
    info.size = len(data)
    info.mode = mode
    info.mtime = int(datetime.now().timestamp())
    tar.addfile(info, io.BytesIO(data))


def add_path(tar: tarfile.TarFile, rel: str) -> int:
    base = ROOT / rel
    files = [base] if base.is_file() else sorted(p for p in base.rglob("*") if p.is_file())
    n = 0
    for p in files:
        parts = p.relative_to(ROOT).parts
        if any(x in SKIP_DIRS for x in parts) or p.suffix in (".pyc", ".map"):
            continue
        data = p.read_bytes()
        if p.suffix in TEXT_SUFFIXES:
            data = data.replace(b"\r\n", b"\n")
        add_bytes(tar, "/".join(parts), data, 0o755 if p.suffix == ".sh" else 0o644)
        n += 1
    return n


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-build", action="store_true", help="do not run npm run build")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")  # Polish text through Windows pipes
    if not args.no_build:
        build_frontend()
    if not (ROOT / "frontend" / "dist" / "index.html").exists():
        sys.exit("frontend/dist is missing — run without --no-build")

    out_dir = ROOT / "release"
    out_dir.mkdir(exist_ok=True)
    out = out_dir / f"dartsense-serwer-{datetime.now():%Y%m%d-%H%M}.tar.gz"
    with tarfile.open(out, "w:gz") as tar:
        count = 0
        for rel in ("backend", "vision", "frontend/dist", "deploy", "pyproject.toml", "README.md",
                    "configs/default.yaml", "configs/central.yaml"):
            count += add_path(tar, rel)
        add_bytes(tar, "deploy/requirements.txt", requirements().encode())
        # The instructions also at the top level, where the person unpacking sees them first.
        add_bytes(tar, "CZYTAJ-MNIE.md", (ROOT / "deploy" / "README-WDROZENIE.md").read_bytes().replace(b"\r\n", b"\n"))
    print(f"\n{count + 2} plików → {out}  ({out.stat().st_size / 1e6:.1f} MB)")
    print("Instrukcja wdrożenia: deploy/README-WDROZENIE.md")


if __name__ == "__main__":
    main()
